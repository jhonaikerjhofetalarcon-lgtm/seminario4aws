-- Crea las tablas; no borra alumnos, matrículas ni datos de otras tablas.
begin;

create table if not exists public.alumnos (
  id integer generated by default as identity primary key,
  nombre text not null,
  edad integer not null,
  constraint alumnos_nombre_valido check (char_length(btrim(nombre)) between 3 and 100),
  constraint alumnos_edad_valida check (edad between 1 and 120)
);

create table if not exists public.matriculas (
  id integer generated by default as identity primary key,
  alumno_id integer not null,
  curso text not null,
  modalidad text not null default 'Presencial',
  constraint matriculas_alumno_id_fkey foreign key (alumno_id)
    references public.alumnos(id) on delete cascade,
  constraint matriculas_alumno_curso_unico unique (alumno_id, curso),
  constraint matriculas_curso_valido check (
    curso in ('Programación I', 'Desarrollo Web', 'Base de Datos', 'Diseño de Interfaces')
  ),
  constraint matriculas_modalidad_valida check (modalidad in ('Presencial', 'Virtual'))
);

-- RLS está activa. No damos acceso directo al navegador ni al rol anónimo.
-- La clave secreta solo la usa Go, que sigue escuchando en localhost.
alter table public.alumnos enable row level security;
alter table public.matriculas enable row level security;
revoke all on table public.alumnos, public.matriculas from anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on table public.alumnos, public.matriculas to service_role;
grant usage, select on sequence public.alumnos_id_seq, public.matriculas_id_seq to service_role;

-- Esta función solo consulta. Obtiene las dos listas en una única fotografía.
create or replace function public.consultar_sistema_academico()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'alumnos', coalesce(
      (select jsonb_agg(to_jsonb(a) order by a.id) from public.alumnos as a),
      '[]'::jsonb
    ),
    'matriculas', coalesce(
      (select jsonb_agg(to_jsonb(m) order by m.id) from public.matriculas as m),
      '[]'::jsonb
    )
  );
$$;

revoke all on function public.consultar_sistema_academico() from public, anon, authenticated;
grant execute on function public.consultar_sistema_academico() to service_role;
notify pgrst, 'reload schema';
commit;
